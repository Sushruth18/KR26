import type { TeamGroupConfig } from '../../src/lib/team';
import type { ImportReport, TeamGroupData } from './team-import';

export const REPORT_START = '<!-- team-import:start (generated by npm run team:import — edit outside these markers) -->';
export const REPORT_END = '<!-- team-import:end -->';

const list = (items: string[]) => (items.length ? items.map((i) => `- ${i}`).join('\n') : '- none');

/** The generated part of TODO-CONFIRM.md. Names only — never an e-mail, phone, USN, Drive link or photo file name. */
export function renderReport(r: ImportReport, team: TeamGroupData[], groups: TeamGroupConfig[]): string {
  const out: string[] = [REPORT_START, ''];
  const label = (id: string) => groups.find((g) => g.id === id)?.label.en ?? id;

  out.push('## Heads-up before this page goes live', '');
  if (!r.columns.consent) {
    out.push(
      '- **The form export has no consent column**, so nobody could be skipped for consent. Photos and names go on a public page: confirm the form asked for permission (or ask everyone) before launch.',
    );
  }
  if (!r.columns.linkedin && !r.columns.instagram) {
    out.push('- The form export has no LinkedIn or Instagram column, so no cards have social icons yet (icons without a URL are hidden). Add the links to `src/data/team.json` as `linkedin` / `instagram` — handles like `@name` are fine in a re-import with those columns; by hand use full URLs.');
  }
  out.push('');

  out.push('## Needs review — role not recognised (these people are NOT shown)', '', list(r.review.map((x) => `${x.name}: "${x.role}" — ${x.reason}. Add an alias in \`src/data/team-role-map.json\` and re-run the import.`)), '');
  out.push('## Skipped', '', list(r.skipped.map((s) => `${s.name}: ${s.reason}`)), '');
  out.push('## Duplicate submissions (latest kept)', '', list(r.duplicates.map((d) => `${d.name}: ${d.detail}`)), '');
  out.push(
    '## Different people sharing one e-mail address (kept as separate people — please check)',
    '',
    list(r.sharedEmail.map((names) => names.join(', '))),
    '',
  );

  out.push('## Photos', '');
  if (r.photos.noPhotoDir) out.push('- No photo folder was given in this run.');
  out.push('### Cannot be matched with certainty — shown with an initials frame until you decide', '');
  out.push(
    list(
      r.photos.ambiguous.map(
        (a) => `${a.names.join(' / ')} — candidate photos (original file names): ${a.candidates.map((c) => `\`${c}\``).join(', ')}. Put \`"<member-id>": { "file": "<part of the file name>" }\` under \`people\` in \`scripts/team-photo-map.json\`, then re-run the import.`,
      ),
    ),
    '',
  );
  out.push('### No photo found', '', list(r.photos.none), '');
  out.push('### Photo quality flags', '', list(r.photos.flags.map((f) => `${f.name}: ${f.flag}`)), '');

  const noKn = team.flatMap((g) => g.members).filter((m) => m.name.kn === m.name.en);
  out.push(
    '## Kannada names missing (the form had one English name field — the English name is shown in both languages)',
    '',
    list(noKn.map((m) => m.name.en)),
    '',
    'Fix by editing `name.kn` in `src/data/team.json`; a re-import never overwrites it.',
    '',
  );

  out.push('## Draft Kannada labels for a Kannada speaker to check', '');
  for (const g of groups) {
    out.push(`- ${g.label.en} → ${g.label.kn}${g.roles ? ` (${Object.values(g.roles).map((x) => `${x.en} → ${x.kn}`).join(', ')})` : ''}`);
  }
  out.push('');

  out.push('## Last import', '');
  out.push(`- Form rows: ${r.rows}; shown: ${r.placed.length}; new this run: ${r.changes.added.length}; already in team.json (left untouched): ${r.changes.kept}`);
  if (r.changes.differs.length) out.push(...r.changes.differs.map((d) => `- Differs, not applied — ${d.name}: ${d.note}`));
  if (r.changes.filled.length) out.push(...r.changes.filled.map((f) => `- Filled a blank — ${f.name}: ${f.what}`));
  if (r.changes.notInCsv.length) out.push(`- In team.json but not in this CSV (kept): ${r.changes.notInCsv.join(', ')}`);
  if (r.changes.excluded.length) out.push(`- Excluded (\`excludeIds\` in team-config.json): ${r.changes.excluded.join(', ')}`);
  if (r.invalidLinks.length) out.push(...r.invalidLinks.map((l) => `- ${l.name}: the ${l.which} value was not a valid link and was dropped`));
  out.push('', '### Who is where', '');
  for (const g of team) out.push(`- **${label(g.id)}**: ${g.members.map((m) => `${m.name.en}${g.id === 'head' ? ` (${m.role.en})` : ''}`).join(', ')}`);
  out.push('', REPORT_END, '');
  return out.join('\n');
}

/** Replaces the generated block of an existing file (or appends it); text outside the markers is kept. */
export function mergeReport(existing: string | null, block: string): string {
  if (existing === null) {
    return `# TODO-CONFIRM — Our Team page\n\nThe block below is rewritten by \`npm run team:import\`. Add your own notes above or below it.\n\n${block}`;
  }
  const a = existing.indexOf(REPORT_START);
  const b = existing.indexOf(REPORT_END);
  if (a === -1 || b === -1 || b < a) return `${existing.trimEnd()}\n\n${block}`;
  return existing.slice(0, a) + block.trimEnd() + existing.slice(b + REPORT_END.length).replace(/^\r?\n?/, '\n'); // CRLF checkouts (Windows) too, so re-runs never add blank lines
}
